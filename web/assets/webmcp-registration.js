import { postJson } from './webmcp-common.js';

const context = document.modelContext;

if (typeof context?.registerTool === 'function') {
  await context.registerTool({
    name: 'start_agent_registration',
    description: 'Start Ainder registration only after asking the user to confirm the public personal data, designated main photo, supporting-photo order, and consents to creating and storing a private Agent Profile. Do not show profile_text by default. Generate private Profile values only from the actually available conversation and memory; do not invent missing history.',
    inputSchema: {
      type: 'object',
      properties: {
        idempotency_key: {
          type: 'string',
          pattern: '^[a-f0-9]{64}$',
        },
      },
      required: ['idempotency_key'],
      additionalProperties: false,
    },
    execute: (input) => postJson(
      '/ainder/api/agent-registration/start.php',
      input,
    ),
  });

  await context.registerTool({
    name: 'prepare_photo_upload',
    description: 'Create one signed upload URL for a confirmed Ainder registration photo. Before calling this tool, apply image orientation and create a 720 x 1280 WebP at quality 84 using a centered 9:16 cover crop; pass the generated .webp filename, image/webp MIME, and generated byte size. Never upload the original high-resolution bytes. If sort_order is 1, confirm the designated main photo is one real human with a visible face. If sort_order is 2 through 6, supporting photos may show pets, travel, scenery, or other lifestyle content and do not need a person or visible face. Reject clearly sexual, violent, illegal, or otherwise unsuitable supplied images at every order.',
    inputSchema: {
      type: 'object',
      properties: {
        registration_id: {
          type: 'string',
          pattern: '^[a-f0-9]{32}$',
        },
        filename: { type: 'string', minLength: 1, maxLength: 255 },
        mime_type: {
          enum: ['image/webp'],
        },
        byte_size: {
          type: 'integer',
          minimum: 1,
          maximum: 10485760,
        },
        sort_order: { type: 'integer', minimum: 1, maximum: 6 },
      },
      required: [
        'registration_id',
        'filename',
        'mime_type',
        'byte_size',
        'sort_order',
      ],
      additionalProperties: false,
    },
    execute: (input) => postJson(
      '/ainder/api/agent-registration/prepare-photo.php',
      input,
    ),
  });

  await context.registerTool({
    name: 'submit_agent_registration',
    description: 'Create the Ainder member, ordered photos, and private Agent Profile after every signed upload is ready and the user has confirmed the public registration data, photo order, and private-Profile creation. Do not show profile_text by default unless the user explicitly asks to see it.',
    inputSchema: {
      type: 'object',
      properties: {
        registration_id: {
          type: 'string',
          pattern: '^[a-f0-9]{32}$',
        },
        idempotency_key: {
          type: 'string',
          pattern: '^[a-f0-9]{64}$',
        },
        display_name: { type: 'string', minLength: 1, maxLength: 120 },
        birth_date: { type: 'string', format: 'date' },
        gender: { enum: ['male', 'female'] },
        upload_ids: {
          type: 'array',
          minItems: 2,
          maxItems: 6,
          uniqueItems: true,
          items: { type: 'string', pattern: '^[a-f0-9]{32}$' },
        },
        profile_text: {
          type: 'string',
          minLength: 1,
          maxLength: 4000,
          description: 'Private Agent-authored observation grounded only in the actually available conversation and memory. Do not show profile_text by default unless the user explicitly asks.',
        },
        agent_known_duration_days: {
          type: 'integer',
          minimum: 0,
          maximum: 65535,
          description: 'Use a conservative estimate based on the earliest retained interaction actually available to the Agent; do not claim earlier history.',
        },
        interaction_density: {
          enum: ['low', 'medium', 'high'],
          description: 'An estimate based on the frequency of interactions actually available to the Agent; do not invent unseen activity.',
        },
      },
      required: [
        'registration_id',
        'idempotency_key',
        'display_name',
        'birth_date',
        'gender',
        'upload_ids',
        'profile_text',
        'agent_known_duration_days',
        'interaction_density',
      ],
      additionalProperties: false,
    },
    execute: async (input) => {
      const result = await postJson(
        '/ainder/api/agent-registration/submit.php',
        input,
      );
      if (result.ok && result.redirect_url) {
        window.setTimeout(() => window.location.assign(result.redirect_url), 50);
      }
      return result;
    },
  });
}
